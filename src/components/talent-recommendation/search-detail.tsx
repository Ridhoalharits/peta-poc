import { InfoNote } from "@/components/shared/info-note";
import { PageTitle } from "@/components/shared/page-title";
import type { SearchView } from "@/lib/search-view";
import type { CandidateSearch, SearchResult } from "@/lib/types";
import { FailedView } from "./failed-view";
import { NotFoundView } from "./not-found-view";
import { ProcessingView } from "./processing-view";
import { ResultsActions } from "./results-actions";
import { ResultsTable } from "./results-table";

interface SearchDetailProps {
  view: SearchView;
  search: CandidateSearch;
  /** Ranked results; used by the found view. */
  results: SearchResult[];
}

function FoundView({ results }: { results: SearchResult[] }) {
  return (
    <>
      <ResultsTable results={results} />
      <InfoNote>Scores and justifications are generated by PETA&apos;s matching model. Review them before making any decision.</InfoNote>
    </>
  );
}

/** The body of /talent-recommendation/[id]: one of the four views. Actions show only in the found view. */
export function SearchDetail({ view, search, results }: SearchDetailProps) {
  return (
    <>
      <PageTitle title="Search Results" actions={view === "found" ? <ResultsActions searchId={search.id} /> : undefined} />
      {view === "processing" && <ProcessingView />}
      {view === "found" && <FoundView results={results} />}
      {view === "not-found" && <NotFoundView searchId={search.id} />}
      {view === "failed" && <FailedView searchId={search.id} />}
    </>
  );
}
